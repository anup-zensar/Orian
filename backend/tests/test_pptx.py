"""Support model PPT builder (spec 10.6.2): exactly five slides, footer, landscape content."""

from __future__ import annotations

import io

from pptx import Presentation

from app.services.mock.support_model_generator import MockSupportModelGenerator
from app.services.pptx_support_model import TEMPLATE_NAME, build_support_model_pptx, theme

META = {
    "transition_name": "Medallia VOC",
    "portfolio": "GCC",
    "version": 2,
    "date": "2026-11-16",
    "reviewed_by": "Asha",
}


def _texts(slide):
    out = []
    for shape in slide.shapes:
        if shape.has_text_frame:
            out.append(shape.text_frame.text)
        if getattr(shape, "has_table", False) and shape.has_table:
            out.extend(c.text for row in shape.table.rows for c in row.cells)
    return "\n".join(out)


def _open(landscape, meta=META):
    return Presentation(io.BytesIO(build_support_model_pptx(landscape, meta)))


def _voc():
    return MockSupportModelGenerator().generate({"name": "Medallia VOC"}, {})


def test_five_slides_16_9_and_footer():
    prs = _open(_voc())
    assert len(prs.slides) == 5
    assert prs.slide_width * 9 == prs.slide_height * 16
    for slide in prs.slides:
        assert "Confidential" in _texts(slide)
        assert TEMPLATE_NAME in _texts(slide)


def test_title_and_landscape_slides():
    prs = _open(_voc())
    first = _texts(prs.slides[0])
    assert "Support model - Medallia VOC" in first and "GCC" in first and "2026-11-16" in first
    assert "Draft - generated by Orion, reviewed by Asha" in first
    second = _texts(prs.slides[1])
    assert "Medallia VOC" in second
    for name in ("GCC Integration", "SSO", "SPN", "MDH"):
        assert name in second
    assert "Medallia + KPMG:" in second and "• Hosting" in second
    assert "Medallia is:" in second


def test_arrowheads_follow_relation():
    shapes = _open(_voc()).slides[1].shapes
    xml = "".join(s._element.xml for s in shapes if "Connector" in s.name)
    assert "a:tailEnd" in xml and "a:headEnd" in xml


def test_flow_contacts_questions_slides():
    prs = _open(_voc())
    flow = _texts(prs.slides[2])
    assert "L1" in flow and "L3" in flow and "Escalation" in flow
    contacts = _texts(prs.slides[3])
    assert "KPMG" in contacts and "SLA" in contacts
    last = _texts(prs.slides[4])
    assert "Confirm L2/L3 split" in last and "Architecture diagram p.3" in last


def test_minimal_and_hostile_landscape():
    landscape = {
        "central_app": "Tiny\x00 app",
        "components": [
            {"id": "c1", "name": "X" * 300, "type": "T", "relation": "child_of:Missing"}
        ],
    }
    meta = {"transition_name": "T", "portfolio": "P", "version": 1, "date": "2026-01-01"}
    prs = _open(landscape, meta)
    assert len(prs.slides) == 5
    assert "Tiny app" in _texts(prs.slides[1])


def test_theme_is_single_source():
    t = theme()
    assert t["footer"] == "Confidential" and len(t["header_bg"]) == 6


def test_questions_slide_shows_answers_and_lists_open_ones():
    landscape = {
        **_voc(),
        "open_questions": [
            {"question": "Who owns L2?", "answer": "The vendor"},
            {"question": "Who is on call?", "answer": "  "},
            "Where is it hosted?",  # a landscape stored before answers existed
        ],
    }
    text = _texts(_open(landscape).slides[4])
    answered, open_part = text.split("\nOpen questions\n", 1)
    assert "Q: Who owns L2?" in answered and "A: The vendor" in answered
    assert "1. Who is on call?" in open_part and "2. Where is it hosted?" in open_part
    assert "Who owns L2?" not in open_part


def test_questions_slide_without_answers_keeps_the_open_list():
    text = _texts(_open(_voc()).slides[4])
    assert "Answered questions" not in text and "1. Confirm L2/L3 split" in text
