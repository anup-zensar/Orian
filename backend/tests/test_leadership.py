"""Leadership updates (FR-080): generate from live data, list, send (mock mail), audit."""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import select

from app.models import AuditEvent, GateReview, LeadershipUpdate, OutboxMessage

API = "/api/v1"
SECTIONS = (
    "## Headline",
    "## Status by portfolio",
    "## Top risks and blockers",
    "## Decisions due in the next 30 days",
    "## Asks for leadership",
    "## Wins",
)


def _generate(client, headers, scope, scope_id=None, user="U01"):
    body = {"scope": scope, **({"scope_id": scope_id} if scope_id else {})}
    return client.post(f"{API}/orion/leadership-update", json=body, headers=headers(user))


def test_generate_all_portfolio_transition(client, headers, fresh_seed):
    for scope, sid, title in (
        ("all", None, "Leadership update - all transitions"),
        ("portfolio", "GCC", "Leadership update - GCC portfolio"),
        ("transition", "TR-0001", "Leadership update - Mobility Knowledge Agent (TR-0001)"),
    ):
        res = _generate(client, headers, scope, sid)
        assert res.status_code == 200, res.text
        out = res.json()
        assert out["title"] == title and out["scope"] == scope and out["scope_id"] == sid
        assert out["generated_by"]["id"] == "U01" and out["generated_source"] == "Orion agent"
        assert out["content_md"].startswith(f"# {title}") and out["sent_at"] is None
        for section in SECTIONS:
            assert section in out["content_md"]
        assert "Generated by Orion agent" in out["content_md"]
    assert _generate(client, headers, "transition", "TR-0001", "U16").status_code == 200


def test_generate_errors_and_permissions(client, headers):
    assert _generate(client, headers, "all", user="U15").status_code == 403
    assert _generate(client, headers, "all", user="U10").status_code == 403
    assert _generate(client, headers, "transition", "TR-9999").status_code == 404
    assert _generate(client, headers, "portfolio", "Nope").status_code == 404
    assert _generate(client, headers, "all", "GCC").status_code == 400
    assert _generate(client, headers, "portfolio").status_code == 400
    assert (
        client.post(
            f"{API}/orion/leadership-update", json={"scope": "x"}, headers=headers("U01")
        ).status_code
        == 422
    )


