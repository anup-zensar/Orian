def test_list_and_detail(client, headers, fresh_seed):
    first = _generate(client, headers, "all").json()
    second = _generate(client, headers, "portfolio", "GCC").json()
    rows = client.get(f"{API}/leadership-updates", headers=headers("U15")).json()
    assert [r["id"] for r in rows][:2] == [second["id"], first["id"]]
    one = client.get(f"{API}/leadership-updates/{first['id']}", headers=headers("U15"))
    assert one.status_code == 200 and one.json()["content_md"] == first["content_md"]
    assert client.get(f"{API}/leadership-updates/99999", headers=headers("U15")).status_code == 404
    assert client.get(f"{API}/leadership-updates").status_code == 401


def test_send_via_mock_mail_is_audited(client, db, headers, fresh_seed):
    update = _generate(client, headers, "portfolio", "GCC").json()
    url = f"{API}/leadership-updates/{update['id']}/send"
    assert (
        client.post(
            url, json={"to": ["laura.evans@example.com"]}, headers=headers("U15")
        ).status_code
        == 403
    )
    assert client.post(url, json={"to": []}, headers=headers("U01")).status_code == 422
    assert client.post(
        url, json={"to": ["not-an-address"]}, headers=headers("U01")
    ).status_code in (400, 422)
    assert (
        client.post(
            f"{API}/leadership-updates/9999/send", json={"to": ["a@b.co"]}, headers=headers("U01")
        ).status_code
        == 404
    )
    res = client.post(
        url, json={"to": ["laura.evans@example.com", "head@example.com"]}, headers=headers("U01")
    )
    assert res.status_code == 200, res.text
    out = res.json()
    assert out["sent_at"] and out["sent_to"] == ["laura.evans@example.com", "head@example.com"]
    mail = db.scalars(select(OutboxMessage).where(OutboxMessage.subject == update["title"])).one()
    assert mail.channel == "Email" and mail.from_address == "orion-noreply@example.com"
    assert "<h4>" in mail.body_html and "<script" not in mail.body_html
    event = db.scalars(
        select(AuditEvent).where(
            AuditEvent.entity == "LeadershipUpdate", AuditEvent.action == "sent"
        )
    ).one()
    assert event.actor_type == "Human" and event.note == "Sent leadership update to 2 recipients"
    assert db.get(LeadershipUpdate, update["id"]).sent_at is not None
    again = client.post(url, json={"to": ["a@b.co"]}, headers=headers("U16"))
    assert again.status_code == 200 and again.json()["sent_to"] == ["a@b.co"]
    detail = client.get(f"{API}/leadership-updates/{update['id']}", headers=headers("U15")).json()
    assert detail["sent_to"] == ["a@b.co"]


def test_generation_is_audited_as_orion_and_changes_no_status(client, db, headers, fresh_seed):
    res = _generate(client, headers, "transition", "TR-0001")
    event = db.scalars(
        select(AuditEvent).where(
            AuditEvent.entity == "LeadershipUpdate", AuditEvent.action == "generated"
        )
    ).one()
    assert event.actor_type == "Orion agent" and event.actor_user_id == "U01"
    assert event.note.startswith("Orion drafted the leadership update for ")
    assert event.transition_id == "TR-0001" and str(res.json()["id"]) == event.entity_id


