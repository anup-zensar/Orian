"""Orion agent: insights (M2); chat, proposals, leadership updates arrive in M8 (FR-090, FR-080,
BR-050)."""

from __future__ import annotations

from typing import Annotated, Literal

from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from app.deps import get_current_user, get_db
from app.domain.insights import build_insights
from app.models import User
from app.schemas.orion import InsightsOut
from app.schemas.transitions import TransitionFilters

router = APIRouter(tags=["orion"], dependencies=[Depends(get_current_user)])


@router.get("/orion/insights", response_model=InsightsOut)
def get_insights(
    filters: Annotated[TransitionFilters, Query()],
    scope: Literal["dashboard", "control-tower", "transition"] = Query(...),
    scope_id: str | None = Query(
        default=None, alias="id", description="Transition id when scope=transition"
    ),
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> InsightsOut:
    """3–5 Orion insights generated by ``AIService.insights`` from live data (FR-010, FR-011).
    Read-only: insights only link or propose – they never change data (BR-050).
    For scope=control-tower the optional TransitionFilters query params narrow the view so the
    card matches the filtered control tower; other scopes ignore them."""
    return build_insights(db, user, scope, scope_id, filters)
