def extract_intake(
    text: str, vocab: Mapping[str, Any], servicenow: Mapping[str, Any] | None = None
) -> IntakeExtraction:
    """Deterministic intake extractor (spec 8.4). No DB, no network, no randomness; every list is
    iterated in sorted order and ties are broken alphabetically. All matching is against ``vocab``
    (built from the DB by ``domain.nl_intake.build_vocabulary``) - there is NO hard-coded project type,
    portfolio, region, option, role or person in this function.

    Normalisation: lower-case, accents stripped, ``-_/`` -> space, punctuation removed, plural "s"
    ignored, whitespace collapsed. ``match(phrase, candidates)`` scores each candidate (its name and
    its ``synonyms``) against the text: 1.0 whole-phrase match on word boundaries; 0.9 all words of the
    candidate present within a 6-word window; 0.75 ``difflib.SequenceMatcher`` ratio >= 0.85 on a
    window of the same length; else no match. One best candidate (>= 0.9) -> state "found"
    (0.75-0.9 -> "inferred"); two or more candidates tied within 0.05 -> "ambiguous" with the
    candidates and no value. Confidence = the score.

    Fields:
    * ServiceNow id ``PRJ\\d+`` (case-insensitive) -> ``servicenow_project_id`` (upper-case). When
      ``servicenow`` is given its values fill name, project_type, portfolio, region, market,
      investment_type, delivery_method, description and the PM user (source "servicenow", confidence
      1.0 when the value is in vocab, otherwise state "missing" with the note "ServiceNow value not in
      the list").
    * name: text after the cues ``called|named|project|solution|transition|for`` up to a comma, " in ",
      " - " or line end (<= 80 chars, quotes stripped); else the ``Subject:`` line (prefixes Re:/Fwd:
      removed); else the first non-empty line of a document when it is <= 80 chars and has no ":";
      else missing.
    * project_type, portfolio, region and each ``options`` list: ``match`` over the vocab lists.
      Yes/no style options: an option starting with "No"/"None" is chosen by "no <field words>",
      "without" or "none"; otherwise only the option text or its synonyms are matched (admin-extendable
      through ``orion_synonyms``).
    * people: for every user in ``vocab["users"]`` the full name or - when unique across users - the
      first name is searched (``match``); the user fills the role picker of its own role
      (``vocab["role_fields"]``); two users of the same role matching -> a role cue within 40
      characters before/after the name (role code or label from ``vocab["roles"]``, e.g. "architect
      Mei", "Mei (OLM)") decides, else "ambiguous". A first name shared by several users is ambiguous
      unless a full name or cue is given.
    * dates: ISO ``yyyy-mm-dd``; ``d Mon yyyy`` / ``Mon d(, yyyy)`` (English month names; missing year
      = next occurrence after ``vocab["today"]``); ``dd/mm/yyyy`` (day first). The date nearest after a
      cue ``decision|go[- ]live|launch|deadline|gate|by|due`` -> ``next_decision_date``; several cues
      with different dates -> "ambiguous".
    * ``sites`` (only when the matched portfolio has ``requires_sites``): regex rows
      ``site\\s*(?:id)?\\s*[:#]?\\s*([A-Za-z0-9-]{3,})[\\s,;(]+(?:site\\s*)?key\\s*[:#]?\\s*([A-Za-z0-9-]+)``
      and two-column lines ``<id>, <key>`` under a "sites" heading.
    * description: the first 2 sentences of the text when ServiceNow gave none (<= 400 chars).
    ``evidence`` is the matched words (<= 300 chars). ``summary`` is "Found N of M fields"."""
    raise NotImplementedError("M8")


def parse_command(
    message: str,
    catalog: Sequence[Mapping[str, Any]],
    vocab: Mapping[str, Any],
    context: Mapping[str, Any],
) -> list[ParsedCommand]:
    """Deterministic command parser for free text.

    1. Split the message into clauses on ``;``, newlines, `` and then ``, `` and `` before a verb and
       ``. `` (max 5 clauses, order kept).
    2. Intent per clause = highest score over ``catalog`` entries: +3 for each catalog example whose
       significant words (stop words removed) are all present, +2 per verb cue word (cue words are
       derived from the catalog ``examples`` and ``label`` at call time, not a second list), +1 per
       argument actually found. Refusal intents win on their cue words (approve, sign off, accept,
       reject, close, delete, clear, "send now", "act as", "pretend") and on a request to change project
       types, portfolios or users. Score < 3 -> clause ignored.
    3. Arguments are resolved against ``vocab`` with the same ``match`` as ``extract_intake``:
       transition by id ``TR-\\d+`` or name; item ids ``[A-Za-z]+\\d*-\\d+`` (upper-cased); users by name
       (first name when unique); gate by code or short name; dates: ISO, ``d Mon``, ``Mon d``,
       ``dd/mm``, today / tomorrow, ``(next )?<weekday>`` (the next one strictly after
       ``context["today"]``), ``in N days|weeks``, ``end of (the )?month``; priority words from the
       ``priorities`` vocab; status words from the item-status vocab of the item's lens; title = clause
       minus the matched verb / owner / date / item tokens (<= 120 chars).
    4. ``missing`` = required args of the catalog entry that were not found; ``ambiguous`` = args with
       several candidates. Never returns an intent absent from ``catalog``; nothing found -> [].
    Same input -> same output."""
    raise NotImplementedError("M8")
